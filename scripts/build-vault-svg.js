#!/usr/bin/env node
/* Ports the quantum page's vault drawing to the landing (2026-09-08).
   public/quantum.html holds the ONE copy of the vault SVG (generated in turn
   by tools/vault-gen.js: never hand-edit the paths). This script lifts that
   <svg id="vtSvg"> verbatim into src/generated/vault-svg.ts so the landing's
   Three Problems panel renders the very same drawing, and it runs inside
   `npm run build`, so the two cannot drift. Dies non-zero if the drawing
   cannot be found. */
const fs = require('fs');
const path = require('path');
const src = fs.readFileSync(path.join(__dirname, '..', 'public', 'quantum.html'), 'utf8');
const a = src.indexOf('<svg id="vtSvg"');
if (a < 0) { console.error('build-vault-svg: <svg id="vtSvg"> not found in public/quantum.html'); process.exit(1); }
const b = src.indexOf('</svg>', a);
if (b < 0) { console.error('build-vault-svg: unterminated vault svg'); process.exit(1); }
const svg = src.slice(a, b + 6).replace(/^\s+/gm, '');
const out = `/* GENERATED by scripts/build-vault-svg.js from public/quantum.html; do not edit.
   The vault drawing the quantum page's Head Start tab 02 shows, verbatim,
   so the landing's Three Problems panel and /quantum render one device. */
export const VAULT_SVG = ${JSON.stringify(svg)};
`;
const dest = path.join(__dirname, '..', 'src', 'generated', 'vault-svg.ts');
const prev = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : '';
if (prev !== out) fs.writeFileSync(dest, out);
console.log('vault-svg.ts: ' + svg.length + ' chars' + (prev === out ? ' (unchanged)' : ' (written)'));
